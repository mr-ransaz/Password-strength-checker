"""Generate a PyInstaller Windows version resource from source package metadata."""

import argparse
import ast
import re
import tomllib
from collections.abc import Sequence
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def package_version(root: Path) -> str:
    """Read the source version without importing or executing package code."""
    source = (root / "src/pwcheck/__init__.py").read_text(encoding="utf-8")
    tree = ast.parse(source)
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(
            isinstance(target, ast.Name) and target.id == "__version__"
            for target in node.targets
        ):
            version = ast.literal_eval(node.value)
            break
    else:
        raise ValueError("Source package version is missing.")
    with (root / "pyproject.toml").open("rb") as metadata:
        project_version = tomllib.load(metadata)["project"]["version"]
    if not isinstance(version, str) or version != project_version:
        raise ValueError("Source and project versions must match.")
    return version


def version_resource(version: str) -> str:
    """Render a numeric x.y.z version as a Windows version-resource expression."""
    if re.fullmatch(r"[0-9]+\.[0-9]+\.[0-9]+", version) is None:
        raise ValueError("Windows release version must be numeric x.y.z.")
    parts = tuple(map(int, version.split("."))) + (0,)
    if any(part > 65535 for part in parts):
        raise ValueError("Windows version components must fit unsigned 16-bit fields.")
    return f"""# Generated by scripts/windows_version.py; do not hand-edit.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={parts!r}, prodvers={parts!r},
    mask=0x3f, flags=0x0, OS=0x40004, fileType=0x1, subtype=0x0, date=(0, 0)
  ),
  kids=[
    StringFileInfo([
      StringTable('040904B0', [
        StringStruct('FileDescription', 'Password strength checker'),
        StringStruct('FileVersion', {version!r}),
        StringStruct('InternalName', 'pwcheck'),
        StringStruct('OriginalFilename', 'pwcheck.exe'),
        StringStruct('ProductName', 'password-strength-checker'),
        StringStruct('ProductVersion', {version!r})
      ])
    ]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""


def main(argv: Sequence[str] | None = None) -> int:
    """Print the source version or write its generated Windows resource file."""
    parser = argparse.ArgumentParser(description=__doc__)
    destination = parser.add_mutually_exclusive_group(required=True)
    destination.add_argument("--print-version", action="store_true")
    destination.add_argument("--output", type=Path)
    arguments = parser.parse_args(argv)
    version = package_version(ROOT)
    resource = version_resource(version)
    if arguments.print_version:
        print(version)
    else:
        arguments.output.parent.mkdir(parents=True, exist_ok=True)
        arguments.output.write_text(resource, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
